// Command gen builds unmask's tables.go from the Unicode security + UCD data
// files. UTS-39 confusables (skeleton) update on a faster cadence than UTS-46 and
// a skeleton is never a lookup key, so this is safe to re-run and commit freely on
// each Unicode release — unlike the pinned idna vendor.
//
//	go run ./internal/gen                 # fetch the pinned version from unicode.org
//	go run ./internal/gen -dir <path>     # read confusables.txt/Scripts.txt from a local dir
//	go run ./internal/gen -v 16.0.0       # a different Unicode version
//
// It writes ../../tables.go (relative to this package) — i.e. the repo root.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"net/http"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"time"
)

func main() {
	version := flag.String("v", "15.1.0", "Unicode version")
	dir := flag.String("dir", "", "read data files from this local dir instead of fetching")
	out := flag.String("o", "tables.go", "output file")
	flag.Parse()

	conf := load(*version, *dir, "security", "confusables.txt")
	scripts := load(*version, *dir, "ucd", "Scripts.txt")

	skeleton := parseConfusables(conf)
	ranges := parseScripts(scripts)

	if err := emit(*out, *version, skeleton, ranges); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
	fmt.Printf("gen: wrote %s — %d confusable mappings, %d script ranges (Unicode %s)\n",
		*out, len(skeleton), len(ranges), *version)
}

// load returns the bytes of a data file, from -dir if set else fetched from
// unicode.org (security/<v>/<name> or <v>/ucd/<name>).
func load(version, dir, kind, name string) []byte {
	if dir != "" {
		b, err := os.ReadFile(filepath.Join(dir, name))
		must(err)
		return b
	}
	var url string
	if kind == "security" {
		url = fmt.Sprintf("https://www.unicode.org/Public/security/%s/%s", version, name)
	} else {
		url = fmt.Sprintf("https://www.unicode.org/Public/%s/ucd/%s", version, name)
	}
	c := &http.Client{Timeout: 60 * time.Second}
	resp, err := c.Get(url)
	must(err)
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		must(fmt.Errorf("GET %s: %s", url, resp.Status))
	}
	b, err := readAll(resp.Body)
	must(err)
	return b
}

// parseConfusables reads confusables.txt "source ; target-seq ; MA" rows into a
// rune -> prototype-string skeleton map.
func parseConfusables(b []byte) map[rune]string {
	m := make(map[rune]string)
	sc := bufio.NewScanner(strings.NewReader(string(b)))
	sc.Buffer(make([]byte, 0, 64*1024), 1<<20)
	for sc.Scan() {
		line := sc.Text()
		if i := strings.IndexByte(line, '#'); i >= 0 {
			line = line[:i]
		}
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		f := strings.Split(line, ";")
		if len(f) < 2 {
			continue
		}
		src := hexRune(strings.TrimSpace(f[0]))
		var t strings.Builder
		for _, h := range strings.Fields(strings.TrimSpace(f[1])) {
			t.WriteRune(hexRune(h))
		}
		if src != 0 && t.Len() > 0 {
			m[src] = t.String()
		}
	}
	must(sc.Err())
	return m
}

type scriptRange struct {
	lo, hi rune
	script string
}

// parseScripts reads Scripts.txt "LO..HI ; Script" (or "CP ; Script") rows.
func parseScripts(b []byte) []scriptRange {
	var out []scriptRange
	sc := bufio.NewScanner(strings.NewReader(string(b)))
	sc.Buffer(make([]byte, 0, 64*1024), 1<<20)
	for sc.Scan() {
		line := sc.Text()
		if i := strings.IndexByte(line, '#'); i >= 0 {
			line = line[:i]
		}
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		f := strings.Split(line, ";")
		if len(f) != 2 {
			continue
		}
		rng, script := strings.TrimSpace(f[0]), strings.TrimSpace(f[1])
		lo, hi := rng, rng
		if i := strings.Index(rng, ".."); i >= 0 {
			lo, hi = rng[:i], rng[i+2:]
		}
		out = append(out, scriptRange{hexRune(lo), hexRune(hi), script})
	}
	must(sc.Err())
	sort.Slice(out, func(i, j int) bool { return out[i].lo < out[j].lo })
	return out
}

func emit(path, version string, skeleton map[rune]string, ranges []scriptRange) error {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by internal/gen from Unicode %s; DO NOT EDIT.\n\n", version)
	b.WriteString("package unmask\n\n")
	fmt.Fprintf(&b, "// unicodeVersion is the Unicode release these tables were generated from.\n")
	fmt.Fprintf(&b, "const unicodeVersion = %q\n\n", version)

	// confusable: sorted by key for a stable, diffable generated file.
	keys := make([]rune, 0, len(skeleton))
	for k := range skeleton {
		keys = append(keys, k)
	}
	sort.Slice(keys, func(i, j int) bool { return keys[i] < keys[j] })
	b.WriteString("// confusable maps a rune to its UTS-39 skeleton prototype (confusables.txt MA).\n")
	fmt.Fprintf(&b, "var confusable = map[rune]string{\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "\t0x%04X: %q,\n", k, skeleton[k])
	}
	b.WriteString("}\n\n")

	b.WriteString("type scriptRange struct{ lo, hi rune; script string }\n\n")
	b.WriteString("// scriptRanges is Scripts.txt sorted by lo for binary search.\n")
	b.WriteString("var scriptRanges = []scriptRange{\n")
	for _, r := range ranges {
		fmt.Fprintf(&b, "\t{0x%04X, 0x%04X, %q},\n", r.lo, r.hi, r.script)
	}
	b.WriteString("}\n")

	return os.WriteFile(path, []byte(b.String()), 0o644)
}

func hexRune(s string) rune {
	n, err := strconv.ParseInt(strings.TrimSpace(s), 16, 32)
	if err != nil {
		return 0
	}
	return rune(n)
}

func readAll(r interface{ Read([]byte) (int, error) }) ([]byte, error) {
	var out []byte
	buf := make([]byte, 32*1024)
	for {
		n, err := r.Read(buf)
		out = append(out, buf[:n]...)
		if err != nil {
			if err.Error() == "EOF" {
				return out, nil
			}
			return out, nil
		}
	}
}

func must(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}
